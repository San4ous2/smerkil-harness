"""Human-in-the-loop confirmation for dangerous tool calls.

Same model as Claude Code PreToolUse prompts / Hermes approvals: before a
matching tool executes, the run PAUSES and asks the human on the terminal.
The human's decision is deterministic — the model cannot skip, fake or
social-engineer it (the prompt is printed by us, the answer is typed by the
human, never generated by the LLM).

Configuration — <workspace>/confirm.yaml:

    confirm:
      tools:            # tool names that always require confirmation
        - run_shell
        - git_commit
      patterns:         # confirmed only when args match a regex
        - tool: run_shell
          match: "rm -rf|sudo|git push|curl .*(\\|bash|sh)"
      ask_once_per_run: true   # remember approvals within one agent.run()

  # or set SMERKIL_CONFIRM=1 to confirm every shell command
  # or SMERKIL_CONFIRM_ALL=1 to confirm every tool call

If no confirmer is attached (library use, subagents), policy defaults to
deny-with-note: "confirmation required but no human attached" — the safe
direction. `auto_approve=True` (tests, CI) bypasses prompting explicitly.
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional

from .config import load_config_text

# Asker signature: (tool_name, args_str) -> bool (True = approved)
Asker = Callable[[str, str], bool]

# sentinel: distinguishes "no asker passed" (use terminal) from asker=None
# (no human attached at all — always deny)
MISSING = object()


class ConfirmationPolicy:
    def __init__(self, tools: Optional[List[str]] = None,
                 patterns: Optional[List[Dict[str, str]]] = None,
                 ask_once_per_run: bool = True):
        self.tools = set(tools or [])
        self.patterns = [(p.get("tool", "*"),
                          re.compile(p.get("match", r"(?!x)x")))
                         for p in (patterns or [])]
        self.ask_once_per_run = ask_once_per_run
        # per-run approval memory: tool -> set of normalized arg prefixes
        self._approved: Dict[str, set] = {}

    def requires(self, tool_name: str, args_str: str) -> bool:
        if tool_name in self.tools:
            return True
        for ptool, pat in self.patterns:
            if ptool not in ("*", tool_name):
                continue
            if pat.search(args_str or ""):
                return True
        return False

    def already_approved(self, tool_name: str, args_str: str) -> bool:
        if not self.ask_once_per_run:
            return False
        bucket = self._approved.get(tool_name)
        if not bucket:
            return False
        # approve identical repeats of the same call, not everything
        return (args_str or "") in bucket

    def remember(self, tool_name: str, args_str: str) -> None:
        self._approved.setdefault(tool_name, set()).add(args_str or "")

    def reset_run(self) -> None:
        self._approved.clear()


class ConfirmGate:
    """Attaches to the agent loop: ask() before executing flagged calls."""

    def __init__(self, policy: ConfirmationPolicy,
                 asker: Optional[Asker] = None,
                 auto_approve: bool = False):
        self.policy = policy
        # explicit None means "no human attached" — keep it, fail closed
        self.asker = _terminal_asker if asker is MISSING else asker
        self.auto_approve = auto_approve

    def check(self, tool_name: str, args_str: str) -> Optional[str]:
        """Returns None (allowed) or a denial reason string."""
        p = self.policy
        if not p.requires(tool_name, args_str):
            return None
        if self.auto_approve:
            return None
        if p.already_approved(tool_name, args_str):
            return None
        if self.asker is None:
            return ("denied by human: confirmation required but no human is "
                    "attached to this run — the action was not executed. "
                    "Rephrase the goal or remove the sensitive action.")
        approved = False
        try:
            approved = bool(self.asker(tool_name, args_str))
        except KeyboardInterrupt:
            # Ctrl-C at the prompt = decline, never crash the run
            print("\n[confirm] interrupted → denied")
            return "denied by human: interrupted at the confirmation prompt"
        except Exception:
            approved = False
        if approved:
            p.remember(tool_name, args_str)
            return None
        return ("denied by human: the user declined this action. "
                "Do not retry it; finish the goal another way or ask the user what to change.")


def _terminal_asker(tool_name: str, args_str: str) -> bool:
    """Default asker: prompt on the terminal. Runs OUTSIDE the LLM."""
    try:
        if not sys.stdin or not sys.stdin.isatty():
            # non-interactive: nothing to confirm against → deny
            print(f"\n[confirm] {tool_name} requires approval but stdin is not a TTY — denied")
            return False
        print(f"\n\033[33m⚠ confirm\033[0m  {tool_name}({args_str[:400]})")
        while True:
            ans = input("\033[33m  allow? [y/N/a=yes to all identical calls]\033[0m ").strip().lower()
            if ans in ("y", "yes"):
                return True
            if ans in ("a",):
                # 'a' approves this exact call now and identical repeats
                return True
            if ans in ("", "n", "no"):
                return False
    except (EOFError, KeyboardInterrupt):
        print()
        return False


def confirm_from_config(workspace: Path) -> Optional[ConfirmationPolicy]:
    """Load policy from <workspace>/confirm.yaml; None if absent."""
    path = Path(workspace) / "confirm.yaml"
    if not path.exists():
        return None
    try:
        data = load_config_text(path.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[smerkil] confirm.yaml not parseable, confirmations skipped: "
              f"{type(e).__name__}: {str(e)[:200]}")
        return None
    cfg = data.get("confirm")
    if not isinstance(cfg, dict):
        return None
    return ConfirmationPolicy(
        tools=list(cfg.get("tools") or []),
        patterns=list(cfg.get("patterns") or []),
        ask_once_per_run=bool(cfg.get("ask_once_per_run", True)),
    )


def confirm_from_env() -> Optional[ConfirmationPolicy]:
    """SMERKIL_CONFIRM=1 → confirm all run_shell; SMERKIL_CONFIRM_ALL=1 → all tools."""
    if os.environ.get("SMERKIL_CONFIRM_ALL", "").lower() in ("1", "true", "yes"):
        return ConfirmationPolicy(tools=[], patterns=[
            {"tool": "*", "match": r"."}])
    if os.environ.get("SMERKIL_CONFIRM", "").lower() in ("1", "true", "yes"):
        return ConfirmationPolicy(tools=["run_shell"])
    return None
